"""Independent plistlib fixtures and outgoing UI Sync wire validation.

The initial reset/layout scenario uses the public synthetic identifiers from
LIVI ui_sync.rs tests (Lasse Heitgres, GPL-3.0-or-later; see NOTICE).
Run --write only when deliberately updating the checked-in byte fixtures.
"""
from pathlib import Path
import plistlib
import struct
import subprocess
import sys

FIXTURE = Path(__file__).parent / 'support' / 'ui_sync_test_fixtures.h'


def opack(value):
    if value is True:
        return b'\x01'
    if isinstance(value, str):
        value = value.encode('utf-8')
        base = 0x40
    elif isinstance(value, bytes):
        base = 0x70
    elif isinstance(value, dict):
        pairs = b''.join(opack(k) + opack(v) for k, v in value.items())
        return bytes([0xe0 + len(value)]) + pairs if len(value) < 15 else b'\xef'+pairs+b'\x03'
    else:
        raise ValueError(type(value))
    size = len(value)
    if size <= 32:
        return bytes([base + size]) + value
    width = 1 if size < 256 else 2
    return bytes([base + 32 + width]) + size.to_bytes(width, 'little') + value


def frame(header, display='Cluster_Display', extra=True):
    result = {'displayUUID': display}
    if extra:
        result['extension'] = True
    result['data'] = plistlib.dumps(header, fmt=plistlib.FMT_BINARY, sort_keys=False)
    return opack(result)


def command(kind, args=None, psn=3, **fields):
    body = {'type': kind}
    if args is not None:
        body['data'] = args
    header = {'type': 2, 'ssn': 1, 'psn': psn, 'data': plistlib.dumps(body, fmt=plistlib.FMT_BINARY, sort_keys=False)}
    header.update(fields)
    return frame(header)


def fixtures():
    reset = {'type': 0, 'ssn': 1, 'psn': 1, 'asn': 0, 'id': '89858A51', 'version': 3}
    result = {
        'reset': frame(reset),
        'complete': frame({'type': 1, 'ssn': 1, 'psn': 1, 'version': 3}),
        'complete_v1': frame({'type': 1, 'ssn': 1, 'psn': 1, 'version': 1}),
        'version_zero': frame({'type': 1, 'ssn': 1, 'psn': 1, 'version': 0}),
        'basic': frame({'type': 2, 'ssn': 1, 'psn': 2}),
        'layout': command(3, {'layoutID': 'DB7C6944', 'paletteID': 'dark'}, psn=3),
        'palette': command(0x10, {'layoutIdentifier': 'DB7C6944', 'paletteIdentifier': 'red'}, psn=4),
        'appearance': command(0x13, {'preference': 1}, psn=5),
        'focus': command(8, psn=6),
        'no_ack': command(0x13, {'preference': 2}, psn=7, noAck=True),
        'peer_ack': frame({'type': 3, 'ssn': 1, 'psn': 8, 'asn': 5}),
        'future_ack': frame({'type': 3, 'ssn': 1, 'psn': 9, 'asn': 999}),
        'stale': frame({'type': 2, 'ssn': 9, 'psn': 10}),
        'unknown': command(0x40, psn=10),
        'bad_no_ack': frame({'type': 2, 'ssn': 1, 'psn': 11, 'noAck': 1}),
        'bad_command': frame({'type': 2, 'ssn': 1, 'psn': 11, 'data': b'bad-plist'}),
        'wrong_display': frame(reset, display='Other_Display'),
        'id_data': frame(dict(reset, id=b'phone-id')),
        'id_bool': frame(dict(reset, id=True)),
        'id_negative': frame(dict(reset, id=-7)),
        'id_null': frame(dict(reset, id=None)),
        'id_array': frame(dict(reset, id=[1])),
        'id_unicode': frame(dict(reset, id='\u00e9')),
        'large_panel': opack({'displayUUID': 'Cluster_Display', 'extra': b'x'*1100,
                              'data': plistlib.dumps(reset, fmt=plistlib.FMT_BINARY)}),
        'inventory_unknown_layout': command(3, {'layoutID': 'not-installed', 'paletteID': 'dark'}, psn=5),
        'inventory_unknown_palette': command(0x10, {'layoutIdentifier': 'DB7C6944', 'paletteIdentifier': 'not-installed'}, psn=5),
        'inventory_wrong_layout_palette': command(3, {'layoutID': 'DB7C6944', 'paletteID': 'blue'}, psn=5),
        'inventory_layout_only': command(3, {'layoutID': 'DB7C6944'}, psn=5),
    }
    # Introduce a duplicate type key in a real plistlib object table, independent
    # of the SDK writer. Root has fewer than 15 fields and one-byte references.
    duplicate = bytearray(plistlib.dumps(dict(reset, shadow=0), fmt=plistlib.FMT_BINARY, sort_keys=False))
    offset_width, reference_width, _, root, table = struct.unpack('>6xBBQQQ', duplicate[-32:])
    root_offset = int.from_bytes(duplicate[table+root*offset_width:table+(root+1)*offset_width], 'big')
    assert reference_width == 1 and duplicate[root_offset] == 0xd7
    duplicate[root_offset+7] = duplicate[root_offset+1]
    result['duplicate_type'] = opack({'displayUUID': 'Cluster_Display', 'data': bytes(duplicate)})
    dense = {'displayUUID': 'Cluster_Display'}
    dense.update(('extra'+str(i), '') for i in range(62))
    dense['data'] = plistlib.dumps(reset, fmt=plistlib.FMT_BINARY)
    result['dense_panel'] = opack(dense)
    return result


def generated():
    text = '/* SPDX-License-Identifier: GPL-3.0-or-later */\n/* Generated by tests/check_ui_sync_wire.py using Python plistlib. */\n'
    text += '#ifndef UI_SYNC_TEST_FIXTURES_H\n#define UI_SYNC_TEST_FIXTURES_H\n#include <stdint.h>\n#include <stddef.h>\n'
    for name, body in fixtures().items():
        text += 'static const uint8_t ui_fixture_'+name+'[] = {\n'
        for pos in range(0, len(body), 16):
            text += '    '+','.join('0x{:02x}'.format(b) for b in body[pos:pos+16])+',\n'
        text += '};\n'
    text += 'enum { '+', '.join('UI_FIXTURE_'+name for name in fixtures())+' };\n'
    text += 'static const struct { const uint8_t *bytes; size_t length; } ui_fixtures[] = {\n'
    for name in fixtures():
        text += '    {ui_fixture_'+name+', sizeof(ui_fixture_'+name+')},\n'
    return text+'};\n#endif\n'


def decode_opack(body):
    """Independent subset decoder for the generated outgoing panel frames."""
    def read(at):
        tag = body[at]
        at += 1
        if tag in (1, 2):
            return tag == 1, at
        if 0x40 <= tag <= 0x63 or 0x70 <= tag <= 0x93:
            string = tag < 0x70
            size = tag-(0x40 if string else 0x70)
            if size > 32:
                width = size-32
                size = int.from_bytes(body[at:at+width], 'little')
                at += width
            value = body[at:at+size]
            assert len(value) == size
            return value.decode('utf-8') if string else value, at+size
        if 0xe0 <= tag < 0xef:
            result = {}
            for _ in range(tag-0xe0):
                key, at = read(at)
                value, at = read(at)
                assert key not in result
                result[key] = value
            return result, at
        raise AssertionError(hex(tag))
    result, at = read(0)
    assert at == len(body)
    return result


def check(executable):
    assert FIXTURE.read_text() == generated(), 'Regenerate intentional fixture changes with --write'
    output = subprocess.check_output([str(Path(executable).resolve()), '--dump'], text=True)
    messages = []
    for line in output.splitlines():
        if line.startswith('UIHEX '):
            outer = decode_opack(bytes.fromhex(line[6:]))
            assert outer['displayUUID'] == 'Cluster_Display' and outer['extension'] is True
            header = plistlib.loads(outer['data'])
            if 'data' in header:
                header['command'] = plistlib.loads(header['data'])
            messages.append(header)
        elif line.startswith('PLISTHEX '):
            value = plistlib.loads(bytes.fromhex(line[9:]))
            assert value == {'null': None, 'true': True, 'false': False, 'negative': -7,
                             'data': b'\x00\x01\xff', 'items': list(range(16))}
    assert len(messages) >= 20
    reset, complete, allow, layout, focus = messages[:5]
    assert reset == {'type': 0, 'ssn': 1, 'psn': 1, 'asn': 0, 'version': 2, 'id': '89858A51'}
    assert complete == {'type': 1, 'ssn': 1, 'psn': 2, 'asn': 1, 'version': 2, 'id': '89858A51'}
    assert allow['command'] == {'type': 0x11, 'data': {'allow': True}}
    assert layout['command'] == {'type': 5, 'data': {'layoutID': '0D38B526', 'paletteID': 'blue',
        'appearanceMode': 0, 'fadeInNewLayout': True, 'fadeOutOldLayout': True,
        'activeComponents': {'F0786093': '2B28C705'}}}
    assert focus['command'] == {'type': 7, 'data': {'tokenID': 12345}}
    assert [m['psn'] for m in messages[:5]] == [1, 2, 3, 4, 5]
    print('UI Sync: independent plistlib input fixtures and {} outgoing messages validated'.format(len(messages)))


if __name__ == '__main__':
    if sys.argv[1:] == ['--write']:
        FIXTURE.write_text(generated())
    else:
        assert len(sys.argv) == 2
        check(sys.argv[1])
