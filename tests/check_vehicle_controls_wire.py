"""Independent OPACK fixtures and decoding for portable Vehicle controls."""
from pathlib import Path
import plistlib
import struct
import subprocess
import sys
import tempfile
from copy import deepcopy

FIXTURE = Path(__file__).parent/'support/vehicle_control_fixtures.h'

def opack(v):
    if v is None: return b'\x04'
    if isinstance(v, bool): return b'\x01' if v else b'\x02'
    if isinstance(v, int):
        if 0 <= v <= 39: return bytes([8+v])
        return b'\x33'+struct.pack('<q',v)
    if isinstance(v, dict):
        assert len(v)<15
        return bytes([0xe0+len(v)])+b''.join(opack(k)+opack(x) for k,x in v.items())
    if isinstance(v,(str,bytes)):
        base=0x40 if isinstance(v,str) else 0x70
        b=v.encode() if isinstance(v,str) else v
        return (bytes([base+len(b)]) if len(b)<=32 else bytes([base+33,len(b)]))+b
    raise TypeError(type(v))

def wrap(values):
    return opack({'pluginID':0,'pluginData':opack({'command':'controlRequest','transactionID':-7,'values':values})})

def generated():
    cases={
        'mixed':wrap({10:{'level':7},11:None,99:None}),
        'blob':wrap({12:None}),
        'empty':wrap({11:{}}),
        'unknown':wrap({99:None}),
        'refused':wrap({10:{'level':95},11:None}),
        'wrong_type':wrap({10:{'level':'7'}}),
        'overflow':wrap({10:{'level':256}}),
        'unknown_parameter':wrap({10:{'wrong':7}}),
        'missing_parameter':wrap({10:{}}),
        'late_invalid':wrap({10:{'level':7},11:{'unexpected':1}}),
    }
    lines=['/* SPDX-License-Identifier: GPL-3.0-or-later */','/* Generated by tests/check_vehicle_controls_wire.py --write; synthetic IDs only. */','#pragma once']
    for name,body in cases.items():
        lines.append('static const unsigned char control_'+name+'[] = {'+','.join('0x%02x'%b for b in body)+'};')
    return '\n'.join(lines)+'\n'

def decode(body):
    def read(at):
        tag=body[at]; at+=1
        if tag==4: return None,at
        if tag in (1,2): return tag==1,at
        if 8<=tag<=0x2f: return tag-8,at
        if 0x30<=tag<=0x33:
            n=1<<(tag-0x30)
            return int.from_bytes(body[at:at+n],'little',signed=True),at+n
        if 0x40<=tag<=0x64 or 0x70<=tag<=0x94:
            string=tag<0x70; n=tag-(0x40 if string else 0x70)
            if n>32:
                width=n-32;n=int.from_bytes(body[at:at+width],'little');at+=width
            v=body[at:at+n];assert len(v)==n
            return v.decode() if string else v,at+n
        if 0xd0<=tag<0xdf:
            v=[]
            for _ in range(tag-0xd0):
                item,at=read(at);v.append(item)
            return v,at
        if 0xe0<=tag<0xef:
            v={}
            for _ in range(tag-0xe0):
                k,at=read(at);x,at=read(at);assert k not in v;v[k]=x
            return v,at
        raise AssertionError(hex(tag))
    v,n=read(0);assert n==len(body);return v

def check(exe):
    assert FIXTURE.read_text()==generated()
    out=subprocess.check_output([str(Path(exe).resolve()),'--dump'],text=True)
    messages={}
    for line in out.splitlines():
        if line.startswith('CONTROL '):
            _,name,wire=line.split();value=decode(bytes.fromhex(wire))
            messages[name]=decode(value['pluginData']) if name!='info' else value
        if line.startswith('CONTROLINFO '): info=plistlib.loads(bytes.fromhex(line.split()[1]))
    assert messages['mixed']=={'command':'controlResponse','transactionID':-7,
        'values':{10:{'echo':8},11:None},'errors':{99:-6735}}, messages['mixed']
    assert messages['blob']['values']=={12:{'blob':b'\x00\xffdemo'}}
    assert messages['empty']['values']=={11:None}
    plugin=info['vehicleStateProtocolInfo']['pluginConfigs'][0]
    controls=plugin['accessories'][0]['services'][0]['controls']
    assert controls==[
        {'iid':10,'type':1010,'sender':0,'hasResponse':True,'priority':1,
         'requestParameters':[{'name':'level','format':1}], 'responseParameters':[{'name':'echo','format':1}]},
        {'iid':11,'type':1011,'sender':0,'hasResponse':True},
        {'iid':12,'type':1012,'sender':0,'hasResponse':True,'responseParameters':[{'name':'blob','format':11}]}]
    assert len(info['displays'])==1 and info['displays'][0]['type']==110
    assert not {'displayPanels','hevcInfo','uiSyncInfo'} & info.keys()
    cases=[(info,True)]
    for field,value in [('iid',99),('type',99),('sender',1),('hasResponse',False)]:
        other=deepcopy(info)
        other['vehicleStateProtocolInfo']['pluginConfigs'][0]['accessories'][0]['services'][0]['controls'][0][field]=value
        cases.append((other,False))
    other=deepcopy(info)
    other['vehicleStateProtocolInfo']['pluginConfigs'][0]['accessories'][0]['services'][0]['controls'][0]['requestParameters'][0]['format']=10
    cases.append((other,False))
    with tempfile.TemporaryDirectory() as directory:
        path=Path(directory)/'info.bplist'
        for value,expected in cases:
            for order in (True,False):
                path.write_bytes(plistlib.dumps(value,fmt=plistlib.FMT_BINARY,sort_keys=order))
                result=subprocess.check_output([str(Path(exe).resolve()),'--check-info',str(path)],text=True).strip()
                assert result==str(int(expected))
    print('Vehicle controls: independent OPACK request fixtures, responses and plistlib service catalogue PASS')

if __name__=='__main__':
    if sys.argv[1:]==['--write']: FIXTURE.write_text(generated())
    else: check(sys.argv[1])
